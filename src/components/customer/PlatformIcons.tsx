/** Neutral placeholder ring for platforms without a known/custom glyph. */
const FALLBACK_PATH =
  "M12 2a10 10 0 100 20 10 10 0 000-20zm0 5a5 5 0 110 10 5 5 0 010-10z";

export function PlatformGlyph({
  platform,
  size = 20,
  pathOverride,
}: {
  platform: string;
  size?: number;
  /** Custom monochrome path (`d`) — takes precedence over the built-in set. */
  pathOverride?: string | null;
}) {
  const d = (pathOverride && pathOverride.trim()) || GLYPH_PATHS[platform] || FALLBACK_PATH;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
    >
      <path d={d} />
    </svg>
  );
}

/**
 * PlatformButton — soft rounded-square card with monochrome glyph.
 * Desktop: sits in one horizontal row. Mobile: large touch target
 * inside a horizontally scrollable strip.
 */
export function PlatformButton({
  platform,
  label,
  active,
  onClick,
  disabled = false,
  pathOverride,
}: {
  platform: string;
  label: string;
  active: boolean;
  onClick: () => void;
  disabled?: boolean;
  pathOverride?: string | null;
}) {
  return (
    <button
      onClick={onClick}
      disabled={disabled}
      aria-pressed={active}
      className={`flex flex-col items-center gap-2 shrink-0 group ${disabled ? "opacity-40 cursor-not-allowed" : ""}`}
    >
      <span
        className={`w-14 h-14 rounded-2xl border flex items-center justify-center transition-all ${
          active
            ? "fp-violet-soft-bg border-[rgba(139,127,255,0.45)] fp-violet"
            : "fp-panel-raised border-[#262A35] fp-text-dim group-hover:fp-text group-hover:border-[#3A3F4E]"
        }`}
      >
        <PlatformGlyph platform={platform} size={22} pathOverride={pathOverride} />
      </span>
      <span className={`text-[11px] ${active ? "fp-violet font-medium" : "fp-text-faint"}`}>
        {label}
      </span>
    </button>
  );
}
