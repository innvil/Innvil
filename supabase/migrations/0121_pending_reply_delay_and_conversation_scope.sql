-- (1) Per-community configurable human-priority reply delay. Default 45s
-- (was a hardcoded 120s -- see src/lib/moderator/pending-reply.ts's
-- DEFAULT_PENDING_REPLY_DELAY_MS), owner-adjustable between 15 and 120
-- seconds. A community that never sets one uses the default.
alter table communities
  add column if not exists pending_reply_delay_seconds integer not null default 45
    check (pending_reply_delay_seconds between 15 and 120);

-- (2) Widen the pending-reply uniqueness scope to (community, trigger
-- message, deployment) instead of (community, trigger message) alone --
-- a genuine multi-target address ("Kwan and Test, thoughts?") now defers
-- EACH targeted deployment's reply independently (each still respects
-- human/admin priority on its own), so more than one deployment must be
-- able to hold a pending row for the SAME trigger message at once. The
-- original (community, trigger message) constraint still exists as a
-- unique index on watch_pending_replies from migration 0118 -- dropped
-- and replaced here rather than amended in place, since 0118 has already
-- been applied to production.
-- The original inline `unique(community_id, trigger_platform_message_id)`
-- table constraint was auto-named by Postgres (never given an explicit
-- name in 0118) -- looked up dynamically here rather than guessed/hard-
-- coded, since the exact autogenerated (and possibly 63-char-truncated)
-- name isn't reliably predictable.
do $$
declare
  old_constraint_name text;
begin
  select tc.constraint_name into old_constraint_name
  from information_schema.table_constraints tc
  where tc.table_name = 'watch_pending_replies'
    and tc.constraint_type = 'UNIQUE'
    and exists (
      select 1 from information_schema.constraint_column_usage ccu
      where ccu.constraint_name = tc.constraint_name and ccu.column_name = 'trigger_platform_message_id'
    )
  limit 1;
  if old_constraint_name is not null then
    execute format('alter table watch_pending_replies drop constraint %I', old_constraint_name);
  end if;
end $$;

create unique index if not exists idx_watch_pending_replies_unique
  on watch_pending_replies (community_id, trigger_platform_message_id, deployment_id);

-- (3) Solicitation warning-count expiry (gap 9, explicit product decision):
-- mirrors the existing 30-day scam_strike_count/scam_strike_at pattern
-- (migration 0063) exactly, for consistency -- a solicitation offense more
-- than 30 days old no longer counts toward the ladder, resetting to a
-- fresh first offense. Previously this counter never expired at all; this
-- is a deliberate, explicit decision, not an accident.
alter table moderator_link_warning_state add column if not exists warning_at timestamptz;
